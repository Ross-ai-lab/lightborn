package lightborn.client;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import net.minecraft.client.model.EntityModel;
import net.minecraft.client.model.geom.ModelLayerLocation;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.Identifier;

/**
 * The Light Dragon: a tall pearl-and-gold seraph hovering over his chest in a swan's S, two dawn-coloured wings raised
 * behind him and draped down his sides, a ring of light behind a small bowed head, the tail hanging in a curl beneath
 * him and the pearl of light held before his heart. His shape and motion are generated by
 * {@code tools/generate_dragon.py} into {@code light_dragon_shape.txt}: some 280 parts, each placed relative to its
 * parent, and the waves that move them (the tail swaying, the wings breathing, the mane and whiskers drifting, the
 * ring and the pearl turning).
 */
public final class LightDragonModel extends EntityModel<LightDragonRenderState> {
    public static final ModelLayerLocation LAYER =
            new ModelLayerLocation(Identifier.fromNamespaceAndPath("lightborn", "light_dragon"), "main");
    /** The atlas is laid out in 256 units; the painted skin carries four texels per unit. */
    private static final int ATLAS = 256;

    private record Box(int u, int v, float x, float y, float z, float w, float h, float d) {}

    private record Def(String name, String parent, float[] pose, List<Box> boxes) {}

    private record Motion(String part, float freq, float phase, float[] amp, float spin) {}

    private static final List<Def> DEFS = new ArrayList<>();
    private static final List<Motion> MOTIONS = new ArrayList<>();
    private static float rootY = 24, rootScale = 1;

    static {
        var in = LightDragonModel.class.getResourceAsStream("/lightborn/light_dragon_shape.txt");
        if (in == null) throw new IllegalStateException("light_dragon_shape.txt is missing from the client resources");
        try (var r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            Def last = null;
            for (String line; (line = r.readLine()) != null; ) {
                if (line.isBlank() || line.startsWith("#")) continue;
                String[] f = line.trim().split("\\s+");
                switch (f[0]) {
                    case "root" -> {
                        rootY = Float.parseFloat(f[1]);
                        rootScale = Float.parseFloat(f[2]);
                    }
                    case "part" -> {
                        last = new Def(f[1], f[2], floats(f, 3, 6), new ArrayList<>());
                        DEFS.add(last);
                    }
                    case "box" -> {
                        float[] b = floats(f, 3, 6);
                        last.boxes()
                                .add(new Box(
                                        Integer.parseInt(f[1]),
                                        Integer.parseInt(f[2]),
                                        b[0],
                                        b[1],
                                        b[2],
                                        b[3],
                                        b[4],
                                        b[5]));
                    }
                    case "motion" -> {
                        float[] m = floats(f, 2, 9);
                        MOTIONS.add(
                                new Motion(f[1], m[0], m[1], new float[] {m[2], m[3], m[4], m[5], m[6], m[7]}, m[8]));
                    }
                    default -> {} // bounds, pearl: notes for the server side and for people
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    private static float[] floats(String[] f, int from, int count) {
        float[] out = new float[count];
        for (int i = 0; i < count; i++) out[i] = Float.parseFloat(f[from + i]);
        return out;
    }

    private final ModelPart dragon, head;
    private final ModelPart[] moving;

    public LightDragonModel(ModelPart root) {
        super(root);
        dragon = root.getChild("dragon");
        Map<String, ModelPart> parts = new HashMap<>();
        parts.put("dragon", dragon);
        for (Def d : DEFS) parts.put(d.name(), parts.get(d.parent()).getChild(d.name()));
        head = parts.get("head");
        moving = new ModelPart[MOTIONS.size()];
        for (int i = 0; i < moving.length; i++)
            moving[i] = parts.get(MOTIONS.get(i).part());
    }

    public static LayerDefinition layer() {
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition dragon = mesh.getRoot()
                .addOrReplaceChild(
                        "dragon",
                        CubeListBuilder.create(),
                        PartPose.offset(0, rootY, 0).withScale(rootScale));
        Map<String, PartDefinition> parts = new HashMap<>();
        parts.put("dragon", dragon);
        for (Def d : DEFS) {
            var cubes = CubeListBuilder.create();
            for (Box b : d.boxes()) cubes.texOffs(b.u(), b.v()).addBox(b.x(), b.y(), b.z(), b.w(), b.h(), b.d());
            float[] p = d.pose();
            parts.put(
                    d.name(),
                    parts.get(d.parent())
                            .addOrReplaceChild(
                                    d.name(), cubes, PartPose.offsetAndRotation(p[0], p[1], p[2], p[3], p[4], p[5])));
        }
        return LayerDefinition.create(mesh, ATLAS, ATLAS);
    }

    @Override
    public void setupAnim(LightDragonRenderState state) {
        super.setupAnim(state);
        float t = state.ageInTicks;
        // He gathers out of light: grows from nothing as he manifests, shrinks back as he leaves.
        float a = Math.clamp(state.manifestation, 0, 1);
        a = a * a * (3 - 2 * a);
        float grow = Math.max(.001f, a);
        dragon.xScale *= grow;
        dragon.yScale *= grow;
        dragon.zScale *= grow;
        dragon.y += (float) Math.sin(t * .055f) * .7f;
        for (int i = 0; i < moving.length; i++) {
            Motion m = MOTIONS.get(i);
            ModelPart p = moving[i];
            float s = (float) Math.sin(t * m.freq() + m.phase());
            float[] amp = m.amp();
            p.xRot += amp[0] * s;
            p.yRot += amp[1] * s + t * m.spin();
            p.zRot += amp[2] * s;
            p.x += amp[3] * s;
            p.y += amp[4] * s;
            p.z += amp[5] * s;
        }
        head.yRot += (float) Math.toRadians(Math.clamp(state.yRot, -55, 55));
        head.xRot += (float) Math.toRadians(Math.clamp(state.xRot, -20, 30)) + (float) Math.sin(t * .028f) * .03f;
    }
}
